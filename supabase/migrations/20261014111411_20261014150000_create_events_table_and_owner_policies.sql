/*
# Create owner-scoped events table and deletion policy

1. New Tables
- `events`
- `id` (bigint identity primary key) — stable event identifier used by the app.
- `user_id` (uuid) — authenticated owner, filled automatically from the active session.
- `name` (text) — event title.
- `emoji` (text) — event icon.
- `date` (date) — event date.
- `platforms` (text array) — shopping platforms used for delivery planning.
- `color` (text) — event accent color.
- `bg_color` (text) — event background color.
- `is_recurring` (boolean) — whether the event repeats yearly.
- `profile_id` (text) — optional family profile reference.
- `created_at` (timestamptz) — creation timestamp.

2. Security
- Enable RLS on `events`.
- Authenticated users can only read, create, update, and delete their own events.
- The owner is assigned by `auth.uid()` by default and cannot be changed through an update policy.

3. Important Notes
- Existing browser-only events are not deleted or modified by this migration.
- The frontend will load cloud events after sign-in and will only remove an event from the screen after a successful database delete response.
*/

CREATE TABLE IF NOT EXISTS public.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  emoji text NOT NULL DEFAULT '🎉',
  date date NOT NULL,
  platforms text[] NOT NULL DEFAULT '{}',
  color text NOT NULL DEFAULT '#FFE566',
  bg_color text NOT NULL DEFAULT '#FFFACC',
  is_recurring boolean NOT NULL DEFAULT false,
  profile_id text,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can select their own events" ON public.events;
CREATE POLICY "Users can select their own events"
ON public.events FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own events" ON public.events;
CREATE POLICY "Users can insert their own events"
ON public.events FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own events" ON public.events;
CREATE POLICY "Users can update their own events"
ON public.events FOR UPDATE
TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete their own events" ON public.events;
CREATE POLICY "Users can delete their own events"
ON public.events FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS events_user_id_created_at_idx
ON public.events (user_id, created_at DESC);